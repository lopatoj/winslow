#!/bin/bash
# Fake Winslow hardware on a Linux laptop, using kernel simulation drivers:
#
#   snd-virmidi  a virtual MIDI card with card id "winslow", so the daemon's
#                default output "hw:winslow" works as on the board
#   iio_dummy    an IIO device "winslow-sim" with ADC channels (fixed values)
#   gpio-sim     a simulated GPIO chip whose input lines you toggle by hand
#
# Usage:
#   sudo scripts/sim.sh up          create the devices and target/sim/winslow.toml
#   scripts/sim.sh press <line>     drive a simulated button line high
#   scripts/sim.sh release <line>   drive it low again
#   sudo scripts/sim.sh down        remove everything
set -euo pipefail

CFS=/sys/kernel/config
GPIO_SIM=$CFS/gpio-sim/winslow
IIO_SIM=$CFS/iio/devices/dummy/winslow-sim
LINES=4
ROOT=$(cd "$(dirname "$0")/.." && pwd)
SIM_DIR=$ROOT/target/sim
# The user who ran sudo gets access to the devices.
OWNER=${SUDO_USER:-$USER}

need_root() {
    [[ $EUID -eq 0 ]] || { echo "run with sudo: sudo $0 $*" >&2; exit 1; }
}

pull_file() {
    local dev chip
    dev=$(cat "$GPIO_SIM/dev_name" 2>/dev/null) || { echo "not set up; run: sudo $0 up" >&2; exit 1; }
    chip=$(cat "$GPIO_SIM/bank0/chip_name")
    echo "/sys/devices/platform/$dev/$chip/sim_gpio$1/pull"
}

up() {
    need_root up
    mountpoint -q $CFS || mount -t configfs none $CFS

    # MIDI output.
    if [[ -e /proc/asound/winslow ]]; then
        echo "MIDI: card \"winslow\" already exists"
    elif lsmod | grep -q '^snd_virmidi'; then
        echo "snd-virmidi is already loaded without id=winslow; run: sudo $0 down" >&2
        exit 1
    else
        modprobe snd-virmidi midi_devs=1 id=winslow
        echo "MIDI: virtual card \"winslow\" (hw:winslow)"
    fi

    # Pots.
    modprobe iio_dummy
    [[ -d $IIO_SIM ]] || mkdir "$IIO_SIM"
    echo "IIO:  device \"winslow-sim\" (voltage0 reads 73)"

    # Buttons.
    modprobe gpio-sim
    if [[ ! -d $GPIO_SIM ]]; then
        mkdir "$GPIO_SIM" "$GPIO_SIM/bank0"
        echo $LINES > "$GPIO_SIM/bank0/num_lines"
        echo winslow-sim > "$GPIO_SIM/bank0/label"
        echo 1 > "$GPIO_SIM/live"
    fi
    local chip
    chip=$(cat "$GPIO_SIM/bank0/chip_name")
    chown "$OWNER" "/dev/$chip"
    for ((i = 0; i < LINES; i++)); do chown "$OWNER" "$(pull_file $i)"; done
    echo "GPIO: /dev/$chip, lines 0-$((LINES - 1))"

    mkdir -p "$SIM_DIR"
    cat > "$SIM_DIR/winslow.toml" <<EOF
# Generated by scripts/sim.sh for testing on this machine.
[midi]
device = "hw:winslow"
channel = 1
usb_gadget = false      # no USB device controller here; using snd-virmidi

[adc]
poll_ms = 5
full_scale = 100        # iio_dummy's voltage0 reads 73, so ~0.73

[[input]]
type = "pot"
name = "dummy pot"
device = "winslow-sim"
channel = "voltage0"

[[input]]
type = "button"
name = "button 0"
chip = "$chip"
line = 0

[[input]]
type = "button"
name = "button 1"
chip = "$chip"
line = 1
EOF
    chown -R "$OWNER" "$SIM_DIR"
    echo
    echo "Config: $SIM_DIR/winslow.toml"
}

down() {
    need_root down
    if [[ -d $GPIO_SIM ]]; then
        echo 0 > "$GPIO_SIM/live"
        rmdir "$GPIO_SIM/bank0" "$GPIO_SIM"
    fi
    [[ -d $IIO_SIM ]] && rmdir "$IIO_SIM"
    modprobe -r gpio-sim iio_dummy 2>/dev/null || true
    modprobe -r snd-virmidi 2>/dev/null || echo "snd-virmidi still in use (close MIDI apps), left loaded"
    echo "removed"
}

case ${1:-} in
    up) up ;;
    down) down ;;
    press | release)
        file=$(pull_file "${2:?line number}")
        [[ $1 == press ]] && echo pull-up > "$file" || echo pull-down > "$file"
        ;;
    *) sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
